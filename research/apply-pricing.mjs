// node research/apply-pricing.mjs
// Reads research/competitor-prices.json, averages competitor prices per product + size,
// writes prices.js (loaded by the site after data.js) and research/pricing-report.md.
// Options with no competitor data get no price (shown as "Price on request" on the site).
// Supplier costs (research/supplier-costs.json, private) are only used for the margin columns in the report.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1")), "..");
const ctx = {}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, "data.js"), "utf8") + ";this.PRODUCTS = PRODUCTS;", ctx);
const { PRODUCTS } = ctx;
const raw = JSON.parse(fs.readFileSync(path.join(ROOT, "research/competitor-prices.json"), "utf8"));
const costFile = path.join(ROOT, "research/supplier-costs.json");
const COSTS = fs.existsSync(costFile) ? JSON.parse(fs.readFileSync(costFile, "utf8")).costs : {};

// competitor product name → our product id
const NAME_TO_ID = {
  "retatrutide": "glp1-r", "tirzepatide": "glp1-t", "cagrilintide": "cagrilintide", "eloralintide": "eloralintide",
  "mots-c": "mots-c", "selank": "selank", "semax": "semax", "vip": "vip", "snap-8": "snap-8",
  "ipamorelin": "ipamorelin", "sermorelin": "glp1-s", "bpc-157": "bpc-157", "tb-500": "tb-500",
  "bpc-157+tb-500": "bpc-tb", "klow": "klow", "glow": "glow", "slu-pp-332": "slu-pp-332", "ghrp-2": "ghrp-2",
  "epitalon": "epitalon", "kpv": "kpv", "melanotan ii": "melanotan-2", "mt2": "melanotan-2", "melanotan i": "melanotan-1", "mt1": "melanotan-1",
  "adamax": "adamax", "ss-31": "ss-31", "igf-1 lr3": "igf-1-lr3", "gonadorelin": "gonadorelin", "nad+": "nad",
  "tesamorelin": "tesamorelin", "cjc-1295+ipamorelin": "cjc-ipa", "cjc-1295 no dac": "cjc-1295", "cjc-1295": "cjc-1295",
  "dihexa": "dihexa", "vesugen": "vesugen", "pt-141": "pt-141", "cortagen": "cortagen", "cartalax": "cartalax",
  "oxytocin": "oxytocin", "thymalin": "thymalin", "ghk-cu": "ghk-cu", "dsip": "dsip", "5-amino-1mq": "5-amino-1mq",
  "kisspeptin-10": "kisspeptin-10", "lipo-c": "lipo-c",
};

// map a competitor mg string onto one of our option labels
function matchLabel(p, mgStr) {
  const m = String(mgStr).trim().toLowerCase().replace(/\s*mg$/, "");
  for (const s of p.sizes) {
    const l = s.label.toLowerCase();
    if (l === `${m} mg`) return s.label;
    const blend = m.match(/^([\d.]+)\s*\+\s*([\d.]+)$/);                       // "5+5" → "BPC 5 mg + TB 5 mg"
    if (blend && new RegExp(`\\b${blend[1]} mg \\+ \\w+ ${blend[2]} mg`).test(l)) return s.label;
    if (m === l || (m.includes("without") && l.includes("without")) || (m.includes("with b12") && !m.includes("without") && l === "with b12")) return s.label;
  }
  if (p.sizes.length === 1 && p.sizes[0].label === "Standard vial") return p.sizes[0].label;   // MT1/MT2/SLU: size unknown on supplier list
  return null;
}

const buckets = {}; const unmatched = [];
for (const r of raw.prices) {
  const id = NAME_TO_ID[String(r.product).toLowerCase()];
  const p = PRODUCTS.find((x) => x.id === id);
  const label = p && matchLabel(p, r.mg);
  if (!label || !(r.price > 0) || /capsule/i.test(r.mg)) { unmatched.push(r); continue; }   // capsules ≠ vials
  ((buckets[id] ??= {})[label] ??= []).push(r);
}

const round = (n) => Math.round(n) - 0.01;   // $88.4 → $87.99, $88.6 → $88.99
// Manual prices — win over the competitor average.
// GLP1-R (2026-10-15): a per-mg ladder matched to Mile High / Rebirth at 5 mg ($54.99) and just under the market above
// that; the averages had put 5 mg above 10 mg and copied one outlier for 60 mg.
const OVERRIDES = {
  tesamorelin: { "10 mg": 79.99 },
  "bac-water": { "3 ml": 5 },   // no competitor data; set 2026-10-17
  "mots-c": { "40 mg": 140 },   // set by hand 2026-10-20, level with Rebirth Labs ($139.99)
  "cjc-ipa": { "CJC 10 mg + Ipa 10 mg": 75 },   // set by hand 2026-10-20
  "glp1-r": { "5 mg": 54.99, "10 mg": 72.99, "20 mg": 129.99, "30 mg": 164.99, "40 mg": 199.99, "60 mg": 269.99 },
};
const prices = {}; const rows = [];
for (const p of PRODUCTS) for (const s of p.sizes) {
  const pts = buckets[p.id]?.[s.label] ?? [];
  const v = pts.map((x) => x.price), n = v.length;
  const mean = n ? v.reduce((a, b) => a + b, 0) / n : null;
  const price = OVERRIDES[p.id]?.[s.label] ?? (n ? round(mean) : null);
  if (price != null) (prices[p.id] ??= {})[s.label] = price;
  rows.push({ name: p.name, label: s.label, cost: COSTS[p.id]?.[s.label] ?? null, n, min: n ? Math.min(...v) : null, max: n ? Math.max(...v) : null, mean, price });
}

fs.writeFileSync(path.join(ROOT, "prices.js"),
  `// Generated by research/apply-pricing.mjs from competitor-prices.json (${raw.collected}). Do not edit by hand.\n` +
  `const PRICES = ${JSON.stringify(prices, null, 1)};\n` +
  `PRODUCTS.forEach((p) => p.sizes.forEach((s) => { const v = PRICES[p.id]?.[s.label]; if (v != null) s.price = v; }));\n`);

const $ = (n) => (n == null ? "—" : `$${n.toFixed(2)}`);
const margin = (price, cost) => (price == null || cost == null ? "—" : `${Math.round(((price - cost) / price) * 100)}%`);
let md = `# Pricing vs. competitors\n\nCollected ${raw.collected} from ${raw.vendors.length} vendors: ${raw.vendors.map((v) => v.name).join(", ")}.\n\n` +
  `Retail price = mean of competitor prices for that compound and size, rounded to .99. Where no competitor listed that size there is no price; the site shows "Price on request" and it is marked **no data**.\n\n` +
  `Margins are shown two ways because the supplier sheet says "1 kit = 10 vials": if the listed cost is per vial, and if it is per 10-vial kit (cost ÷ 10).\n\n` +
  `| Compound | Option | Supplier cost | Competitors (n) | Min | Max | Mean | Our price | Margin if cost is per vial | Margin if cost is per kit |\n|---|---|---|---|---|---|---|---|---|---|\n` +
  rows.map((r) => `| ${r.name} | ${r.label} | ${$(r.cost)} | ${r.n || "**no data**"} | ${$(r.min)} | ${$(r.max)} | ${$(r.mean)} | ${$(r.price)} | ${margin(r.price, r.cost)} | ${margin(r.price, r.cost == null ? null : r.cost / 10)} |`).join("\n") +
  `\n\n## Competitor rows not matched to a catalog option (${unmatched.length})\n\n` +
  (unmatched.length ? unmatched.map((r) => `- ${r.vendor}: ${r.product} ${r.mg} — $${r.price}`).join("\n") : "None.") + "\n";
fs.writeFileSync(path.join(ROOT, "research/pricing-report.md"), md);

const priced = rows.filter((r) => r.n).length;
console.log(`${priced}/${rows.length} options priced from competitor data; ${rows.length - priced} price on request; ${unmatched.length} rows unmatched`);
